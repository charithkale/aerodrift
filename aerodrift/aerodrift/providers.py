"""State providers: an in-memory mock cloud and a real AWS (boto3) collector.

Both expose the same two things: `async fetch()` -> CloudState and `.ec2`, a
client with boto3's `revoke_security_group_ingress` signature, so remediation
code generated by AeroDrift runs unchanged against either.
"""
from __future__ import annotations

import asyncio
import copy
import time

from .models import CloudState, Instance, Rule, SecurityGroup, Subnet


# ------------------------------------------------------------------- mock
class MockEC2:
    """Mimics the subset of the boto3 EC2 client that AeroDrift uses."""

    def __init__(self, cloud: "MockCloud"):
        self._cloud = cloud
        self.calls: list = []

    @staticmethod
    def _rules(perm: dict) -> list:
        proto = perm["IpProtocol"]
        lo, hi = perm.get("FromPort", 0), perm.get("ToPort", 65535)
        out = []
        for r in perm.get("IpRanges", []):
            out.append(Rule(proto, lo, hi, cidr=r["CidrIp"]))
        for r in perm.get("Ipv6Ranges", []):
            out.append(Rule(proto, lo, hi, cidr=r["CidrIpv6"]))
        for p in perm.get("UserIdGroupPairs", []):
            out.append(Rule(proto, lo, hi, source_sg=p["GroupId"]))
        return out

    def revoke_security_group_ingress(self, GroupId, IpPermissions):
        self.calls.append(("revoke", GroupId, IpPermissions))
        sg = self._cloud.state.sgs[GroupId]
        for perm in IpPermissions:
            for rule in self._rules(perm):
                if rule not in sg.ingress:
                    raise KeyError("InvalidPermission.NotFound: %s" % rule.key)
                sg.ingress.remove(rule)
        return {"Return": True}

    def authorize_security_group_ingress(self, GroupId, IpPermissions):
        self.calls.append(("authorize", GroupId, IpPermissions))
        sg = self._cloud.state.sgs[GroupId]
        for perm in IpPermissions:
            for rule in self._rules(perm):
                if rule not in sg.ingress:
                    sg.ingress.append(rule)
        return {"Return": True}


class MockCloud:
    name = "mock"

    def __init__(self, state: CloudState | None = None):
        self.state = state or sample_cloud()
        self.ec2 = MockEC2(self)

    async def fetch(self) -> CloudState:
        await asyncio.sleep(0)                      # behave like real async I/O
        snap = copy.deepcopy(self.state)
        snap.captured_at = time.time()
        return snap


def sample_cloud() -> CloudState:
    """A small 3-tier production VPC: bastion + web (public), app, RDS database."""
    st = CloudState()
    st.subnets = {"subnet-pub-a": Subnet("subnet-pub-a", "vpc-prod", True),
                  "subnet-priv-a": Subnet("subnet-priv-a", "vpc-prod", False)}
    corp = "203.0.113.0/24"
    st.sgs = {
        "sg-bastion": SecurityGroup("sg-bastion", "bastion", "vpc-prod", [Rule("tcp", 22, 22, cidr=corp)]),
        "sg-web": SecurityGroup("sg-web", "web", "vpc-prod", [Rule("tcp", 443, 443, cidr="0.0.0.0/0")]),
        "sg-app": SecurityGroup("sg-app", "app", "vpc-prod", [Rule("tcp", 8080, 8080, source_sg="sg-web")]),
        "sg-db": SecurityGroup("sg-db", "database", "vpc-prod", [Rule("tcp", 5432, 5432, source_sg="sg-app")]),
    }
    st.instances = {
        "i-bastion": Instance("i-bastion", "bastion-1", "subnet-pub-a", ["sg-bastion"], "ec2", "bastion"),
        "i-web": Instance("i-web", "web-1", "subnet-pub-a", ["sg-web"], "ec2", "web"),
        "i-app": Instance("i-app", "app-1", "subnet-priv-a", ["sg-app"], "ec2", "app"),
        "db-prod": Instance("db-prod", "orders-db", "subnet-priv-a", ["sg-db"], "rds", "database"),
    }
    return st


# -------------------------------------------------------------------- AWS
class AwsProvider:
    """Real AWS collector. Requires boto3 and read-only credentials (see README).

    All describe_* calls run concurrently in worker threads (boto3 is blocking).
    NOTE: this class has not been exercised against a live account in this repo's
    test-suite; the mock provider covers the same interface.
    """
    name = "aws"

    def __init__(self, region: str = "us-east-1", profile: str | None = None):
        try:
            import boto3
        except ImportError as exc:                  # pragma: no cover
            raise RuntimeError("boto3 is required for the AWS provider: pip install boto3") from exc
        session = boto3.Session(profile_name=profile, region_name=region)
        self.ec2 = session.client("ec2")
        self._rds = session.client("rds")

    @staticmethod
    def _rules(perm: dict) -> list:
        proto = perm.get("IpProtocol", "tcp")
        lo, hi = perm.get("FromPort", 0), perm.get("ToPort", 65535)
        out = [Rule(proto, lo, hi, cidr=r["CidrIp"]) for r in perm.get("IpRanges", [])]
        out += [Rule(proto, lo, hi, cidr=r["CidrIpv6"]) for r in perm.get("Ipv6Ranges", [])]
        out += [Rule(proto, lo, hi, source_sg=p["GroupId"]) for p in perm.get("UserIdGroupPairs", [])]
        return out

    def _sgs(self):
        out = {}
        for page in self.ec2.get_paginator("describe_security_groups").paginate():
            for g in page["SecurityGroups"]:
                rules = [r for p in g.get("IpPermissions", []) for r in self._rules(p)]
                out[g["GroupId"]] = SecurityGroup(g["GroupId"], g["GroupName"], g.get("VpcId", ""), rules)
        return out

    def _subnets(self):
        out = {}
        for page in self.ec2.get_paginator("describe_subnets").paginate():
            for s in page["Subnets"]:       # approximation: public == auto-assigns public IPs
                out[s["SubnetId"]] = Subnet(s["SubnetId"], s["VpcId"], bool(s.get("MapPublicIpOnLaunch")))
        return out

    def _instances(self):
        out = {}
        for page in self.ec2.get_paginator("describe_instances").paginate():
            for r in page["Reservations"]:
                for i in r["Instances"]:
                    tags = {t["Key"]: t["Value"] for t in i.get("Tags", [])}
                    out[i["InstanceId"]] = Instance(
                        i["InstanceId"], tags.get("Name", i["InstanceId"]), i.get("SubnetId", ""),
                        [g["GroupId"] for g in i.get("SecurityGroups", [])], "ec2", tags.get("role", "app"))
        return out

    def _databases(self):
        out = {}
        for page in self._rds.get_paginator("describe_db_instances").paginate():
            for d in page["DBInstances"]:
                subnets = d.get("DBSubnetGroup", {}).get("Subnets", [])
                out[d["DBInstanceIdentifier"]] = Instance(
                    d["DBInstanceIdentifier"], d["DBInstanceIdentifier"],
                    subnets[0]["SubnetIdentifier"] if subnets else "",
                    [g["VpcSecurityGroupId"] for g in d.get("VpcSecurityGroups", [])], "rds", "database")
        return out

    async def fetch(self) -> CloudState:
        sgs, subnets, ec2s, dbs = await asyncio.gather(
            asyncio.to_thread(self._sgs), asyncio.to_thread(self._subnets),
            asyncio.to_thread(self._instances), asyncio.to_thread(self._databases))
        return CloudState(sgs=sgs, subnets=subnets, instances={**ec2s, **dbs}, captured_at=time.time())
